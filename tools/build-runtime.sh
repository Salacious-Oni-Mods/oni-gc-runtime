#!/usr/bin/env bash
# Build mono-2.0-bdwgc.dll from the checkout tools/fetch-mono.sh made.
#
# The MSBuild properties are Unity's own, copied from
# external/buildscripts/build_runtime_vs.pl at ea2b094:
#   Configuration=Release;Platform=x64;MONO_TARGET_GC=boehm;MONO_USE_STATIC_C_RUNTIME=true
# Only the Runtime\libmono-dynamic target is built (Unity-build.md names it). The rest of
# mono.sln is not needed for the DLL.
#
#   tools/build-runtime.sh                  # toolset = whatever VS defaults to (v145 on VS 2026)
#   TOOLSET=v142 tools/build-runtime.sh     # force a toolset. Unity shipped v142 (MSVC 14.29)
#   MAP=1 ...                               # also write a link.exe /MAP next to the log, which
#                                           # names every function
#   PATCH=b3-markbits ...                   # apply patches/b3-markbits/ first (mono.patch to the mono
#                                           # checkout, bdwgc.patch to external/bdwgc), and
#                                           # revert them afterwards, whatever happens
#
# A patched runtime names itself: mono.patch adds an oni_gc_version() export to boehm-gc.c, and
# this script writes the header it returns from, mono/metadata/oni-gc-version.h, as
# "<patches/<set>/VERSION>-<set>+<commit>", with "*" when this repo's tree is dirty. The
# header is deleted again with the revert. The GC Timing mod's watermark shows it as "GC ...".
#
# ONI_GC_BUILD (the Windows folder fetch-mono.sh checked out into) can be set in tools/local.env.
#
# Output: <checkout>\msvc\build\boehm\x64\bin\Release\mono-2.0-bdwgc.dll, and a log next to
# the checkout, plus a copy at <build root>\out\mono-2.0-bdwgc-<toolset>[-<patch>].dll so the
# next build does not overwrite the one being tested. Nothing is copied into any game install.
#
# A patched build refuses to start unless the files its patches touch are unmodified, so a
# half-reverted checkout cannot end up in a build labelled as something else.
set -euo pipefail

HERE="$(cd "$(dirname "$0")/.." && pwd)"
[ -f "$HERE/tools/local.env" ] && . "$HERE/tools/local.env"
: "${ONI_GC_BUILD:?set ONI_GC_BUILD to the Windows folder tools/fetch-mono.sh used, e.g. D:\\oni-gc-build}"
ROOT_WIN="$ONI_GC_BUILD"
ROOT="$(wslpath -u "$ROOT_WIN")"
VSDEV="${VSDEV:-C:\\Program Files\\Microsoft Visual Studio\\18\\Community\\Common7\\Tools\\VsDevCmd.bat}"
TAG="${TOOLSET:-default}"
LOG_WIN="$ROOT_WIN\\build-$TAG${PATCH:+-$PATCH}.log"
PROPS="Configuration=Release;Platform=x64;MONO_TARGET_GC=boehm;MONO_USE_STATIC_C_RUNTIME=true"
[ -n "${TOOLSET:-}" ] && PROPS="$PROPS;PlatformToolset=$TOOLSET"

[ -f "$ROOT/mono/msvc/mono.sln" ] || { echo "build-runtime: no checkout at $ROOT_WIN\\mono. Run tools/fetch-mono.sh." >&2; exit 2; }

PATCH="${PATCH:-}"
LABEL="$TAG${PATCH:+-$PATCH}"
# Each patch file and the repo it applies to, relative to the mono checkout. A plain list, not a
# `... | while read` loop: git.exe reads stdin, and inside such a loop it swallows the remaining
# lines, so only the first patch would be applied.
PATCH_FILES=(mono.patch bdwgc.patch)
PATCH_DIRS=(. external/bdwgc)
patches() {  # apply | revert | check
  local mode="$1" i file dir pdir failed=0
  pdir="$(wslpath -w "$HERE/patches/$PATCH")"
  for i in "${!PATCH_FILES[@]}"; do
    file="${PATCH_FILES[$i]}"; dir="${PATCH_DIRS[$i]}"
    [ -f "$HERE/patches/$PATCH/$file" ] || continue
    case "$mode" in
      check)  (cd "$ROOT/mono/$dir" && git.exe apply --check "$pdir\\$file" </dev/null) ;;
      apply)  (cd "$ROOT/mono/$dir" && git.exe apply "$pdir\\$file" </dev/null) ;;
      revert) (cd "$ROOT/mono/$dir" && git.exe apply -R "$pdir\\$file" </dev/null) ;;
    esac || { [ "$mode" = revert ] && { failed=1; continue; }; return 1; }
    echo "build-runtime: $mode $PATCH/$file in $dir"
  done
  return $failed
}
if [ -n "$PATCH" ]; then
  [ -f "$HERE/patches/$PATCH/expect.txt" ] || { echo "build-runtime: no patches/$PATCH/expect.txt" >&2; exit 2; }
  [ -f "$HERE/patches/$PATCH/VERSION" ] || { echo "build-runtime: no patches/$PATCH/VERSION" >&2; exit 2; }
  patches check || { echo "build-runtime: patches/$PATCH does not apply cleanly (checkout modified or already patched). Refusing." >&2; exit 2; }
  GC_VERSION="$(tr -d '[:space:]' < "$HERE/patches/$PATCH/VERSION")-$PATCH+$(git -C "$HERE" rev-parse --short=7 HEAD)$( [ -n "$(git -C "$HERE" status --porcelain)" ] && echo '*' || true)"
  VERSION_H="$ROOT/mono/mono/metadata/oni-gc-version.h"
  # Armed before applying: a failed second patch must not leave the first one in the checkout.
  trap 'rm -f "$VERSION_H"; patches revert && echo "build-runtime: patches/$PATCH reverted" || echo "build-runtime: REVERT FAILED, the checkout still carries patches/$PATCH" >&2' EXIT
  patches apply
  printf '/* Generated by tools/build-runtime.sh, deleted after the build. */\n#define ONI_GC_VERSION "%s"\n' "$GC_VERSION" > "$VERSION_H"
  echo "build-runtime: runtime version $GC_VERSION"
  echo "build-runtime: applied patches/$PATCH ($(cat "$HERE"/patches/"$PATCH"/*.patch | md5sum | cut -d' ' -f1))"
fi

BAT="$ROOT/build-runtime.bat"
cat > "$BAT" <<BATEOF
@echo off
call "$VSDEV" -arch=amd64 -host_arch=amd64 >nul
$( [ -n "${MAP:-}" ] && echo "set _LINK_=/MAP:$ROOT_WIN\\mono-2.0-bdwgc-$TAG.map" )
cd /d $ROOT_WIN\\mono\\msvc
msbuild mono.sln /m /nologo /v:minimal "/t:Runtime\\libmono-dynamic" "/p:$PROPS" > "$LOG_WIN" 2>&1
exit /b %ERRORLEVEL%
BATEOF

echo "build-runtime: toolset=$TAG log=$LOG_WIN"
rc=0
(cd /mnt/c && cmd.exe /c "$ROOT_WIN\\build-runtime.bat" </dev/null) || rc=$?
LOG="$(wslpath -u "$LOG_WIN")"
grep -E "error C|error LNK|MSB[0-9]+:" "$LOG" | head -20 || true
DLL="$ROOT/mono/msvc/build/boehm/x64/bin/Release/mono-2.0-bdwgc.dll"
if [ "$rc" -eq 0 ] && [ -f "$DLL" ] && [ -n "$PATCH" ]; then
  # A patch that did not reach the compiler still builds, so each set's expect.txt lists strings
  # only its changes put into the DLL, and a build missing one fails.
  if ! missing="$("$HERE/tools/check-strings.py" "$DLL" "$HERE/patches/$PATCH/expect.txt")"; then
    echo "build-runtime: FAILED, the DLL lacks strings patches/$PATCH/expect.txt requires:" >&2
    echo "$missing" | sed 's/^/  /' >&2
    exit 1
  fi
  echo "build-runtime: patches/$PATCH verified in the binary"
fi
if [ "$rc" -eq 0 ] && [ -f "$DLL" ]; then
  mkdir -p "$ROOT/out"
  cp "$DLL" "$ROOT/out/mono-2.0-bdwgc-$LABEL.dll"
  echo "build-runtime: OK $(md5sum "$DLL" | cut -d' ' -f1)  $(stat -c %s "$DLL") bytes -> $ROOT_WIN\\out\\mono-2.0-bdwgc-$LABEL.dll"
else
  echo "build-runtime: FAILED (msbuild exit $rc)" >&2
  exit 1
fi
